export function calculateWizardResult(scores: Record<BusinessForm, number>): WizardResult {
  const entries = Object.entries(scores) as [BusinessForm, number][]
  const [form] = entries.reduce(
    (best, current) => (current[1] > best[1] ? current : best),
    entries[0],
  )

  const result = wizardResults.find((item) => item.form === form)
  if (!result) {
    return wizardResults[0]
  }

  return {
    ...result,
    score: scores[form],
  }
}
